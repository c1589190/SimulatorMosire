package io.mosire.simos.economy.api.market;

/**
 * ★★ <b>运输损耗由谁承担</b>（M2.5 基线合同）：<b>约定由买方承担</b>（其他分担方式后续扩展）。
 *
 * <p>★★ <b>为什么这是批次里的一个显式字段</b>：损耗不是"蒸发得不明不白"的一笔，它有一条**合同归属** —— 同样是 10‰
 * 的在途损耗，买方承担时买方的到货量少、卖方与承运人不亏；卖方承担时反过来。把归属聚合成一个总量数字就会丢掉这一维， 事后任何读数都分不出"谁该少拿"。⇒
 * 每一笔在途分配都带一档，且**不为聚合丢掉**（M2.5 的判据原文）。
 *
 * <p>★ 本批只有 {@link #BUYER} 有写者（M2.5 定案）；{@link #SELLER} / {@link #CARRIER} 是**留位**（其他分担后续扩展），
 * 读数能认出它们、结算暂时不产生它们。
 */
public enum LossBearer {

  /** 买方承担在途损耗（M2.5 基线合同：发运时买方付货款与运费，货权归买方 ⇒ 损耗也归买方）。 */
  BUYER,

  /** 卖方承担（留位，后续扩展）。 */
  SELLER,

  /** 承运人承担（留位，后续扩展）。 */
  CARRIER
}
