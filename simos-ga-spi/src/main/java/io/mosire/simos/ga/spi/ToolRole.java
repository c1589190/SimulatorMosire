package io.mosire.simos.ga.spi;

/**
 * 工具的角色标签（"这个工具能被谁用"里的**角色维**）。
 *
 * <p>★ 用户原话（2026-10-12，设计书 §1 ③/⑤ 逐字）：
 *
 * <blockquote>
 *
 * 「gm工具啊……理论上来说，gm工具的功能实际上和dm没啥区别啊，dm（决策人）用的时候都得过gm审批工具的审批， gm则是要用直接用」「那整个ga-spi吧，其中实现工具实现的各类标签」
 *
 * </blockquote>
 *
 * <p>语义**只有两条**：
 *
 * <ul>
 *   <li>{@link #GM} = 推演人：**直接用**（工具面挂无脑过的 GM 审批链）；
 *   <li>{@link #DM} = 决策人：**过审批**（审批链按**装配**决定——今天是 {@code AutoApproveGate → ConfirmGate →
 *       PendingApprovals}，见设计书 §4.4 派生关系第 4 条）。
 * </ul>
 *
 * <p>★ 同一个工具可以同时声明 {@code {GM, DM}}：设计书 §1 原话 ③ 的裁定是"GM 与 DM 用**同一批工具**， 差别只在审批链"（G-4）。
 *
 * <p>★★ **审批链不在本枚举里**：本枚举只回答"谁能看见 / 谁能调"；"调用时要不要停下来等确认"由装配面决定 （{@code GmAutoApproveGate} 挂在 GM
 * 面）。把审批写进角色会造出第二处真相——那正是本模块要消灭的形态。
 */
public enum ToolRole {

  /** 推演人：直接用（无审批的 GM 面）。 */
  GM,

  /** 决策人：过审批（审批链按装配决定，不在本枚举里）。 */
  DM
}
